-- ========================================================
-- 3사 통합 산업안전보건 관제 시스템 - Supabase 데이터베이스 스키마
-- Supabase Dashboard > SQL Editor에 복사하여 [RUN] 버튼을 누르시면 됩니다.
-- ========================================================

-- 1. 사이트 기본 설정 테이블
CREATE TABLE IF NOT EXISTS public.site_config (
    id BIGINT PRIMARY KEY DEFAULT 1,
    system_name TEXT NOT NULL DEFAULT '3사 통합 산업안전보건 관제 시스템',
    subtitle TEXT DEFAULT '(주)케이프라이드 · (주)보담 · (주)케이펙',
    urgent_notice TEXT,
    base_date TEXT DEFAULT '2026-11-05',
    admin_pin TEXT DEFAULT '1234',
    auto_refresh_sec INT DEFAULT 30,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. 긴급 D-Day 및 알림 테이블
CREATE TABLE IF NOT EXISTS public.alerts (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    level TEXT NOT NULL DEFAULT 'warning', -- critical, warning, info
    title TEXT NOT NULL,
    corp TEXT NOT NULL,
    dday TEXT,
    "desc" TEXT,
    action_text TEXT,
    status TEXT DEFAULT '대기',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. 법정 안전검사 및 설비 점검 현황 테이블
CREATE TABLE IF NOT EXISTS public.inspections (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    corp TEXT NOT NULL,
    equipment_name TEXT NOT NULL,
    location TEXT,
    last_date TEXT,
    next_date TEXT,
    status TEXT DEFAULT '정상(양호)',
    inspector TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. 사내 안전보건 공지사항 테이블
CREATE TABLE IF NOT EXISTS public.safety_notices (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title TEXT NOT NULL,
    corp TEXT DEFAULT '전 법인',
    author TEXT DEFAULT '안전관리자',
    date TEXT,
    is_pinned BOOLEAN DEFAULT FALSE,
    content TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. 법인별 통계 현황 테이블
CREATE TABLE IF NOT EXISTS public.corp_stats (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    corp_name TEXT NOT NULL,
    worker_count INT DEFAULT 0,
    zero_accident_days INT DEFAULT 0,
    risk_assessment_rate INT DEFAULT 0,
    health_check_rate INT DEFAULT 0,
    status_summary TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ========================================================
-- RLS (Row Level Security) 설정 및 익명(anon) 접근 권한 부여
-- 웹 브라우저에서 publishable key로 바로 CRUD 가능하도록 정책 설정
-- ========================================================

ALTER TABLE public.site_config ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alerts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inspections ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.safety_notices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.corp_stats ENABLE ROW LEVEL SECURITY;

-- 기존 정책이 있다면 삭제 후 재생성
DROP POLICY IF EXISTS "Allow anon all on site_config" ON public.site_config;
DROP POLICY IF EXISTS "Allow anon all on alerts" ON public.alerts;
DROP POLICY IF EXISTS "Allow anon all on inspections" ON public.inspections;
DROP POLICY IF EXISTS "Allow anon all on safety_notices" ON public.safety_notices;
DROP POLICY IF EXISTS "Allow anon all on corp_stats" ON public.corp_stats;

CREATE POLICY "Allow anon all on site_config" ON public.site_config FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow anon all on alerts" ON public.alerts FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow anon all on inspections" ON public.inspections FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow anon all on safety_notices" ON public.safety_notices FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow anon all on corp_stats" ON public.corp_stats FOR ALL USING (true) WITH CHECK (true);

