// 한국어 조사 및 어미 정제 함수
function extractKeywords(text) {
  if (!text) return [];
  const cleaned = text.toLowerCase().replace(/[?!.,~^'"·()[\]]/g, ' ');
  const rawWords = cleaned.split(/\s+/).filter(w => w.length > 0);
  
  const tokens = [];
  const suffixRegex = /(에서|으로|까지|부터|에게|한테|이나|이나|는데|했어|했음|했는|하려|하면|하고|되어|되며|떨어트|떨어뜨|어떡함|어쩌죠|알려줘|어떻게|어떡해|인가요|인가|이야|이냐|때문|관련|대처|조치|매뉴얼|수칙|규정|방법|상황|발생|사고|을|를|이|가|에|의|은|는|도|만|로|과|와)$/g;

  for (const w of rawWords) {
    tokens.push(w);
    const stem = w.replace(suffixRegex, '');
    if (stem.length >= 1 && stem !== w) {
      tokens.push(stem);
    }
  }
  return Array.from(new Set(tokens));
}

// 지식 검색 함수 (Smart RAG Retrieval Engine)
function searchSafetyKnowledge(query) {
  const q = query.toLowerCase().trim();
  const tokens = extractKeywords(query);

  const matchedEmergency = [];
  const matchedRules = [];

  // 1. 긴급 SOP 검색
  for (const sop of SAFETY_KNOWLEDGE_BASE.emergencySOP) {
    let score = 0;
    
    // 전체 문장 포함 검사
    for (const kw of sop.keywords) {
      const kwLower = kw.toLowerCase();
      if (q.includes(kwLower)) {
        score += (kwLower.length === 1 ? 4 : 6);
      }
      for (const tok of tokens) {
        if (tok === kwLower) {
          score += 5;
        } else if (tok.includes(kwLower) || kwLower.includes(tok)) {
          if (tok.length >= 2) score += 3;
        }
      }
    }

    if (q.includes(sop.category.toLowerCase())) score += 6;

    if (score > 0) {
      matchedEmergency.push({ sop, score });
    }
  }

  // 2. 안전수칙 검색
  for (const rule of SAFETY_KNOWLEDGE_BASE.safetyRules) {
    let score = 0;
    for (const kw of rule.keywords) {
      const kwLower = kw.toLowerCase();
      if (q.includes(kwLower)) score += 3;
      for (const tok of tokens) {
        if (tok === kwLower) score += 3;
      }
    }
    if (score > 0) {
      matchedRules.push({ rule, score });
    }
  }

  matchedEmergency.sort((a, b) => b.score - a.score);
  matchedRules.sort((a, b) => b.score - a.score);

  return {
    emergency: matchedEmergency.map(item => item.sop),
    rules: matchedRules.map(item => item.rule),
    isEmergencyQuery: matchedEmergency.length > 0 && matchedEmergency[0].score >= 3,
    topScore: matchedEmergency.length > 0 ? matchedEmergency[0].score : 0
  };
}

